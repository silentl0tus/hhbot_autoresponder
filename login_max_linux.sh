#!/bin/bash
# Переходим в директорию, где лежит сам скрипт
cd "$(dirname "$0")" || { echo "Не удалось перейти в папку скрипта"; read -p "Нажмите Enter для выхода..."; exit 1; }

echo "Переход в папку проекта..."
cd hh-autoresponder || { echo "Не удалось найти папку hh-autoresponder"; read -p "Нажмите Enter для выхода..."; exit 1; }

if [ ! -d ".venv" ]; then
    echo "Сначала запустите run_linux.sh для установки зависимостей!"
    read -p "Нажмите Enter для выхода..."
    exit 1
fi

echo "Активация виртуального окружения..."
source .venv/bin/activate

echo "==========================================="
echo "Запуск авторизации в мессенджере MAX..."
echo "Пожалуйста, войдите в свой аккаунт в открывшемся браузере."
echo "После успешного входа скрипт сохранит сессию и закроется."
echo "==========================================="
python3 manual_login_max.py

echo "Сессия сохранена! Теперь бот может взаимодействовать со скринерами MAX."
read -p "Нажмите Enter для выхода..."
