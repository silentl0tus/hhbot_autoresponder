#!/bin/bash
# ==============================================================================
# Скрипт входа на hh.ru под Linux (универсальный для GUI и безголовых серверов)
# ==============================================================================

cd "$(dirname "$0")" || { echo "Не удалось перейти в папку скрипта"; exit 1; }

cd hh-autoresponder || { echo "Не удалось найти папку hh-autoresponder"; exit 1; }

if [ ! -d ".venv" ] || ! .venv/bin/python -c "import sys" >/dev/null 2>&1; then
    echo "❌ Виртуальное окружение .venv не найдено или повреждено."
    echo "Запустите сначала ./run_linux.sh для автоматической сборки окружения."
    exit 1
fi

source .venv/bin/activate

if [ -n "$DISPLAY" ]; then
    echo "==========================================="
    echo "🖥️ Обнаружен дисплей ($DISPLAY). Запуск графического входа..."
    echo "==========================================="
    python3 manual_login.py
else
    echo "==========================================="
    echo "📟 Дисплей не обнаружен (консольный / серверный режим)."
    echo "Запуск консольной авторизации по OTP-коду (SMS / Email)..."
    echo "==========================================="
    python3 cli_login.py
fi
